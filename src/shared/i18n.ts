export type MessageKey = keyof (typeof MESSAGES)['ja'];

export function resolveLocale(settingsLocale?: Locale): Locale {
  if (settingsLocale === 'ja' || settingsLocale === 'en') return settingsLocale;
  try {
    const uiLocale = chrome?.i18n?.getUILanguage?.();
    if (uiLocale && !uiLocale.toLowerCase().startsWith('ja')) return 'en';
  } catch {
    // chrome.i18n が使えない環境（テスト等）では既定の ja にフォールバック
  }
  return 'ja';
}

export function t(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const template = MESSAGES[locale][key] ?? MESSAGES.ja[key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce<string>(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template,
  );
}
